    private void bttnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bttnLoginActionPerformed
        String username = txtUsername.getText().trim();
        String password = new String(PasswordField.getPassword()).trim();
        
        if(username.isEmpty() || password.isEmpty()){
            JOptionPane.showMessageDialog(this, "Please enter username and password");
            return;
        }
        if (username.equals("owner")&& password.equals("owner123")){
            new Dashboard().setVisible(true);
            return;
        }
        try(Connection conn = getConnection()){
            String sql = "SELECT * FROM user WHERE username=? AND password=?";
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, username);
            pst.setString(2, password);
            ResultSet rs = pst.executeQuery();
            
            if(rs.next()){
                openDashboard();
            }else{
                JOptionPane.showMessageDialog(this, "Access Denied! Only owner can login");
                PasswordField.setText("");
            }
        }catch (Exception e){
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_bttnLoginActionPerformed

    private void openDashboard(){
            JOptionPane.showMessageDialog(this, "Welcome Owner!");
            new Dashboard().setVisible(true);
            this.dispose();
        }
