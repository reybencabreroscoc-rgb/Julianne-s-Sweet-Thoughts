    private void bttnGenerateReportsActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bttnGenerateReportsActionPerformed
     if (dcStartDate.getDate() == null || dcEndDate.getDate() == null) {

        JOptionPane.showMessageDialog(this, "Please select both Start Date and End Date.");
        return;
    }
    String start = sdf.format(dcStartDate.getDate());
    String end = sdf.format(dcEndDate.getDate());

    if (start.compareTo(end) > 0) {
        JOptionPane.showMessageDialog(this, "Start Date must not be later than End Date.");
        return;
    }
    loadSalesReport(start, end, showingArchived);
    }//GEN-LAST:event_bttnGenerateReportsActionPerformed

