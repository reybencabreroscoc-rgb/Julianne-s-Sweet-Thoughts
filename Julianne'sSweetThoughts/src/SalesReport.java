    private void loadSalesReport(String startDate, String endDate, boolean archived) {
    DefaultTableModel model = (DefaultTableModel) tblSalesRecord.getModel();
    model.setRowCount(0); 
    double grandTotalSales = 0.0;
    int totalCompletedOrders = 0;
    showingArchived = archived;

    String sql = "SELECT s.sales_id, s.sales_date, s.transaction_number, s.total_amount "
            + "COALESCE((SELECT SUM(si.items_sold) FROM sales_item_id si WHERE si.sales_id = s.sales_id),0) AS items_sold"
            +"FROM sales s WHERE s.is_archived = ?";
    
    boolean hasFilter = startDate !=null && !startDate.isEmpty() && endDate !=null&& !endDate.isEmpty();
    if (hasFilter) {
        sql +="AND DATE (s.sales_date) BETWEEN ? AND ? ";
    }
    sql += "ORDER BY s.sales_date DESC";

    try (Connection conn = getConnection();
         PreparedStatement pstmt = conn.prepareStatement(sql)) {
        pstmt.setInt(1, archived ? 1 : 0);

        if (hasFilter) {
            pstmt.setString(1, startDate);
            pstmt.setString(2, endDate);
        }       
        ResultSet rs = pstmt.executeQuery();
            int rowNumber = 1;
            while (rs.next()) {
                double amount = rs.getDouble("total_amount");
                grandTotalSales += amount;
                totalCompletedOrders++;
                
                model.addRow(new Object[]{
                    rowNumber++,
                    rs.getDate("sales_date"),
                    rs.getString("transaction_number"),
                    rs.getInt("items_sold"),
                    String.format("₱%.2f", amount)
                });   
            }
        
         lblTotalSales.setText(String.format("₱%.2f", grandTotalSales));
        lblCompletedOrder.setText(String.valueOf(totalCompletedOrders));
                     
    
    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Load Error: " + e.getMessage(),
                "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        e.printStackTrace();
    }
}
    private void loadSummaryTotals(){
        try(Connection conn = getConnection()){
            ResultSet rs1 = conn.prepareStatement("SELECT COALESCE(SUM(total_amount),0)FROM sales WHERE is_archived=0 AND sales_date >= DATE_SUB(NOW(), "
                    + "INTERVAL 7 DAY)").executeQuery();
            if(rs1.next()) lblWeekly.setText(String.format("P%.2f", rs1.getDouble(1)));
            
            ResultSet rs2 = conn.prepareStatement("SELECT COALESCE (SUM(total_amount),0) FROM sales WHERE is_archived=0 AND MONTH(sales_date)=MONTH(NOW())"
                    + "AND YEAR(sales_date)=YEAR(NOW())").executeQuery();
            if(rs2.next()) lblMonthly.setText(String.format("P%.2f", rs2.getDouble(1)));
            
            ResultSet rs3 = conn.prepareStatement("SELECT COALESCE(SUM(total_amount),0) FROM sales WHERE is_archived=0 "
                    + "AND YEAR(sales_date)=YEAR(NOW())").executeQuery();
            if(rs3.next()) lblYearly.setText(String.format("P%.2f", rs3.getDouble(1)));
        }catch(Exception e){
            System.out.println("Summary Error: " +e.getMessage());
        }
    }
    
