    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
    String name = cmbProductName.getSelectedItem().toString();
    String category = cmbCategory.getSelectedItem().toString();
    String priceStr = txtPrice.getText().trim();
    String stockStr = txtStock.getText().trim();

    if (name.isEmpty() || priceStr.isEmpty() || stockStr.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please fill in all product fields.");
        return;
    }

    String sql = "INSERT INTO product (product_name, category, price, stock) VALUES (?, ?, ?, ?)";

    try (java.sql.Connection conn = getConnection();
         java.sql.PreparedStatement pstmt = conn.prepareStatement(sql)) {

        pstmt.setString(1, name);
        pstmt.setString(2, category);
        pstmt.setDouble(3, Double.parseDouble(priceStr));
        pstmt.setInt(4, Integer.parseInt(stockStr));

        pstmt.executeUpdate();
        javax.swing.JOptionPane.showMessageDialog(this, "Product added successfully!");
        clearFields();
        loadProductsFromDB();

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Price and Stock must be valid numbers.");
    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Database Insert Error: " + e.getMessage());
    }

    }//GEN-LAST:event_btnAddActionPerformed

