    private void loadProductsFromDB() {
    javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblProducts.getModel();
    model.setRowCount(0);

    String sql = "SELECT product_id, product_name,category, price, stock FROM product ORDER BY product_id ASC";

    try (java.sql.Connection conn = getConnection();
         java.sql.Statement stmt = conn.createStatement();
         java.sql.ResultSet rs = stmt.executeQuery(sql)) {

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("product_id"),
                rs.getString("product_name"),
                rs.getString("category"),
                String.format("%.2f", rs.getDouble("price")),
                rs.getInt("stock")
            });
        }
    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error loading data: " + e.getMessage());
    }
}
    private void updateCounts(){
        try(Connection conn = getConnection()){
            Statement stmt1 = conn.createStatement();
            ResultSet rs1 = stmt1.executeQuery("SELECT COUNT(*) FROM product");
            if(rs1.next()){
                lblTotalProducts.setText(String.valueOf(rs1.getInt(1))); 
           }
            Statement stmt2 = conn.createStatement();
            ResultSet rs2 = stmt2.executeQuery("SELECT COUNT(*)FROM product WHERE stock <= 20");
            if(rs2.next()){
                lblLowStock.setText(String.valueOf(rs2.getInt(1)));
            }
        }catch(Exception e){
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
        
    }
